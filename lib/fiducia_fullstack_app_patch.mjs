async function exists(p) { try { await fs.access(p); return true; } catch { return false; } }
async function write(rel, content) {
  const abs = path.join(ROOT, rel);
  if ((await exists(abs)) && !FORCE) { console.log('skip ', rel, '(exists; use --force)'); return; }
  if (DRY) { console.log('dry  ', rel); return; }
  await fs.mkdir(path.dirname(abs), { recursive:true });
  await fs.writeFile(abs, content);
  console.log('write', rel);
}
async function patchPackage() {
  const p = path.join(ROOT, 'package.json');
  if (!(await exists(p))) { console.log('package.json not found; run from repo root'); return; }
  const pkg = JSON.parse(await fs.readFile(p, 'utf8'));
  pkg.dependencies ||= {};
  let changed = false;
  for (const [k,v] of Object.entries(DEPS)) if (!pkg.dependencies[k]) { pkg.dependencies[k] = v; changed = true; }
  if (DRY) { console.log('dry  package.json deps'); return; }
  if (changed) await fs.writeFile(p, JSON.stringify(pkg, null, 2) + '\n');
  console.log(changed ? 'patch package.json' : 'skip  package.json deps already present');
}
async function appendFile(rel, marker, text) {
  const p = path.join(ROOT, rel);
  const current = (await exists(p)) ? await fs.readFile(p, 'utf8') : '';
  if (current.includes(marker)) { console.log('skip ', rel, '(already patched)'); return; }
  if (DRY) { console.log('dry  ', rel, 'append'); return; }
  await fs.writeFile(p, current + text);
  console.log('patch', rel);
}
